CREATE OR REPLACE FUNCTION public.gh_call_sessions_guard_active_participants()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $function$
DECLARE v_user_id text;
BEGIN
  IF NEW.status IN ('ringing','accepted') THEN
    FOR v_user_id IN
      SELECT DISTINCT participant_id
      FROM unnest(ARRAY[NEW.caller_id,NEW.callee_id]) AS participants(participant_id)
      ORDER BY participant_id
    LOOP
      PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('gh-call-user:'||v_user_id,0));
    END LOOP;
    IF EXISTS (
      SELECT 1 FROM public.gh_call_sessions existing
      WHERE existing.id IS DISTINCT FROM NEW.id
        AND existing.status IN ('ringing','accepted')
        AND existing.expires_at > pg_catalog.now()
        AND (existing.caller_id IN (NEW.caller_id,NEW.callee_id) OR existing.callee_id IN (NEW.caller_id,NEW.callee_id))
    ) THEN
      RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='USER_ALREADY_IN_CALL';
    END IF;
  END IF;
  RETURN NEW;
END;
