#!/usr/bin/env node
/** RUN377: identity/session service-role ACL and readiness semantics. */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const migration = read('supabase/migrations/20261123145603_gh_identity_session_service_role_grants.sql')
const identity = read('supabase/migrations/20261022010019_gh_pi_identities.sql')
const sessions = read('supabase/migrations/20261022010020_gh_sessions.sql')
const identityStore = read('lib/server/identity/pi-identity-store.ts')
const sessionStore = read('lib/server/identity/session-store.ts')
const readiness = read('lib/server/readiness.ts')
const diagnostic = read('docs/RUN338-PI-AUTH-SUPABASE-DIAGNOSTICS.sql')

assert.match(migration, /REVOKE ALL ON TABLE public\.gh_pi_identities, public\.gh_sessions\s+FROM PUBLIC, anon, authenticated, service_role/)
assert.match(migration, /GRANT SELECT, INSERT, UPDATE\s+ON TABLE public\.gh_pi_identities, public\.gh_sessions\s+TO service_role/)
assert.doesNotMatch(migration, /GRANT[^;]+(?:anon|authenticated|PUBLIC)/i)
assert.match(identity, /ALTER TABLE public\.gh_pi_identities ENABLE ROW LEVEL SECURITY/)
assert.match(sessions, /ALTER TABLE public\.gh_sessions ENABLE ROW LEVEL SECURITY/)
assert.match(identity, /USING \(false\)\s+WITH CHECK \(false\)/)
assert.match(sessions, /USING \(false\)\s+WITH CHECK \(false\)/)
assert.match(identityStore, /method: "GET"/)
assert.match(identityStore, /method: "POST"/)
assert.match(identityStore, /method: "PATCH"/)
assert.match(sessionStore, /method: "GET"/)
assert.match(sessionStore, /method: "POST"/)
assert.match(sessionStore, /method: "PATCH"/)
assert.match(readiness, /probe: "configuration_only" \| "live_read_probe"/)
assert.match(readiness, /export async function evaluateLiveReadiness/)
assert.match(readiness, /limit=0/)
assert.match(readiness, /timeoutMs: 5000/)
assert.match(read('app/api/health/route.ts'), /await evaluateLiveReadiness/)
assert.match(readiness, /service_role SELECT\/INSERT\/UPDATE privileges are not verified/)
assert.match(readiness, /configured_unverified/)
assert.match(readiness, /schemaReadiness\.probe = \"live_read_probe\"/)
assert.match(diagnostic, /service_role_insert_granted/)
assert.match(diagnostic, /service_role_update_granted/)
assert.match(diagnostic, /service_role_select_granted/)
console.log('RUN377 identity/session ACL: 24 assertions passed')
